# ───────────────────────── docx 도우미 ─────────────────────────
def _font(run, size=10, bold=False, color=None):
    run.font.name = FONT; run.font.size = Pt(size); run.font.bold = bold
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    if color: run.font.color.rgb = RGBColor(*color)


def _shade(cell, fill):
    tcPr = cell._element.get_or_add_tcPr(); shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), fill); tcPr.append(shd)


def p(doc, text, size=10, bold=False, align=None, color=None, after=4):
    par = doc.add_paragraph(); r = par.add_run(str(text)); _font(r, size, bold, color)
    if align == 'center': par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.space_after = Pt(after); return par


def h(doc, text, level=1):
    par = doc.add_paragraph(); r = par.add_run(text); _font(r, 14 if level == 1 else 12, True, (15, 61, 110))
    par.paragraph_format.space_before = Pt(14 if level == 1 else 10); par.paragraph_format.space_after = Pt(4)
    if level == 1:
        pPr = par._element.get_or_add_pPr(); bdr = OxmlElement('w:pBdr'); b = OxmlElement('w:bottom')
        b.set(qn('w:val'), 'single'); b.set(qn('w:sz'), '8'); b.set(qn('w:space'), '1'); b.set(qn('w:color'), '0F3D6E'); bdr.append(b); pPr.append(bdr)


def table(doc, header, rows, widths=None, size=9):
    t = doc.add_table(rows=1, cols=len(header)); t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, hd in enumerate(header):
        c = t.rows[0].cells[i]; c.text = ''; r = c.paragraphs[0].add_run(str(hd)); _font(r, size, True); _shade(c, 'EEF2F7')
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''; r = cells[i].paragraphs[0].add_run('' if v is None else str(v)); _font(r, size)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths): row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2); return t


def new_doc(title, subtitle):
    doc = Document()
    for s in doc.sections:
        s.top_margin = Cm(2); s.bottom_margin = Cm(2); s.left_margin = Cm(2); s.right_margin = Cm(2)
    st = doc.styles['Normal']; st.font.name = FONT; st.element.rPr.rFonts.set(qn('w:eastAsia'), FONT); st.font.size = Pt(10)
    p(doc, title, 20, True, 'center', after=2)
    p(doc, subtitle, 10, False, 'center', (90, 90, 90), 2)
    p(doc, f"{PROJECT} · 작성일 {TODAY} · 문서 상태: 초안(데모 기준 자동 생성, 착수 후 확정)", 9, False, 'center', (90, 90, 90), 12)
    return doc


